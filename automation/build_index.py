#!/usr/bin/env python3
"""Rebuild <papers>/README.md and manifest.csv from the files actually present (overwritten by every daily run).
Usage: python3 -I build_index.py --config research-lineage.json
"""
import argparse, csv, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import Config, config_arg, category_dirs  # noqa: E402

TXT = {
    "zh": {"total": "**合计 {t} 篇 | 已下载 {d} | 占位 {p}**(占位 = 0 字节空文件，文件名即标题)",
           "files": ["`summaries.md` — 每篇一句话摘要(如有)", "`manifest.csv` — 机读清单",
                     "`placeholders_todo.md` — 占位论文待下载清单", "`{inbox}/<日期>/` — 爬虫抓到、待审核的新论文",
                     "`{lineage}/lineage.html` — 研究脉络图"],
           "auto": "本文件由 research-lineage 的 automation/build_index.py 自动生成(每日任务会覆盖),请勿手改。",
           "n": "篇", "ph": "占位", "dl": "已下载"},
    "en": {"total": "**{t} papers | downloaded {d} | placeholders {p}** (placeholder = 0-byte file named by title)",
           "files": ["`summaries.md` — one-line summaries (if any)", "`manifest.csv` — machine-readable list",
                     "`placeholders_todo.md` — placeholders to download", "`{inbox}/<date>/` — crawler candidates awaiting review",
                     "`{lineage}/lineage.html` — research lineage map"],
           "auto": "Generated by research-lineage automation/build_index.py (overwritten daily); do not edit by hand.",
           "n": "papers", "ph": "placeholder", "dl": "downloaded"},
}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    config_arg(ap)
    a = ap.parse_args()
    cfg = Config(a.config)
    T = TXT.get(cfg.lang, TXT["en"])
    base = cfg["papers"]
    rows = [["category", "arxiv_id", "filename", "status", "size_kb"]]
    body, tot, dl, ph = [], 0, 0, 0
    for cat in category_dirs(cfg):
        files = sorted(f for f in os.listdir(os.path.join(base, cat)) if f.endswith(".pdf"))
        desc = cfg.categories.get(cat)
        body += [f"## {cat}{' — ' + desc if desc else ''}  ({len(files)} {T['n']})", ""]
        for fn in files:
            size = os.path.getsize(os.path.join(base, cat, fn))
            tot += 1
            if size == 0:
                ph += 1; status, mark = T["ph"], "⬜"
            else:
                dl += 1; status, mark = f"{T['dl']} {size // 1024} KB", "✅"
            body.append(f"- {mark} {fn}")
            rows.append([cat, fn.split("_")[0] if fn[:4].isdigit() else "", fn, status, size // 1024])
        body.append("")
    rel = lambda k: os.path.relpath(cfg[k], base)
    head = [f"# {cfg.get('title') or 'Papers'}", "", T["total"].format(t=tot, d=dl, p=ph), ""]
    head += ["- " + f.format(inbox=rel("inbox"), lineage=rel("lineage")) for f in T["files"]]
    if cfg.get("index_note"):
        head += ["", "> " + cfg.get("index_note")]
    head += ["> " + T["auto"], ""]
    with open(os.path.join(base, "README.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(head) + "\n" + "\n".join(body))
    with open(os.path.join(base, "manifest.csv"), "w", newline="", encoding="utf-8") as f:
        csv.writer(f).writerows(rows)
    print(f"TOTAL {tot} | DOWNLOADED {dl} | PLACEHOLDER {ph}")


if __name__ == "__main__":
    main()
